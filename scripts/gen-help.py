#!/usr/bin/env python3
"""Generate lib/help_topics.g.dart in both Flutter apps from docs/*.md (not docs/historical/).

    python3 scripts/gen-help.py [--check]     # --check exits 1 when a generated file is stale
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APPS = ["app", "admin-app"]

def topics():
    out = []
    for f in sorted((ROOT / "docs").glob("*.md")):
        tid = f.stem.lower()
        out.append(("index" if tid == "readme" else tid, f.read_text()))
    return out

def dart():
    lines = ["// GENERATED by scripts/gen-help.py from docs/. Do not edit.", "// ignore_for_file: lines_longer_than_80_chars", "",
             "const helpTopics = <String, String>{"]
    for tid, md in topics():
        lines.append(f"  {json.dumps(tid)}: {json.dumps(md).replace('$', chr(92) + '$')},")
    lines.append("};")
    return "\n".join(lines) + "\n"

def main():
    s = dart()
    stale = [a for a in APPS if not (ROOT / a / "lib/help_topics.g.dart").exists()
             or (ROOT / a / "lib/help_topics.g.dart").read_text() != s]
    if "--check" in sys.argv:
        if stale:
            print("help topics out of date (run scripts/gen-help.py):", ", ".join(stale)); sys.exit(1)
        print("help: current"); return
    for a in APPS:
        (ROOT / a / "lib/help_topics.g.dart").write_text(s)
    print(f"help: {len(topics())} topics, {len(stale)} files changed")

main()
